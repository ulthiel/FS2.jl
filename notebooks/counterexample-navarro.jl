using Oscar;

# We add one preliminary helper function for the inflation of a character along a projection so that we can conveniently compute the external direct product of characters.
function inflate(theta, pr)
    gap_theta = GAP.Globals.RestrictedClassFunction(
        GapObj(theta),
        GapObj(pr)
    )
    return Oscar.GAPGroupClassFunction(TH, gap_theta)
end;

# ## Section 3.1
# Let G be the small group (960, 11358). We show that G × C4 has a character χ = α ⊠ λ such that FS2(χ) does not hold.

G = small_group(960, 11358)
C4 = cyclic_group(4);
TG = character_table(G)
TC4 = character_table(C4)
α = first(α for α in TG if degree(α)==5 && !is_rational(α))
λ = first(λ for λ in TC4 if is_faithful(λ));

# Now we create the external direct product character χ = α ⊠ λ and show that
# FS2(χ) does not hold.
H, emb, pr = direct_product(G, C4; morphisms = true)
TH = character_table(H)
αH = inflate(α, pr[1])
λH = inflate(λ, pr[2])
χ = αH * λH
#
is_irreducible(χ)
#
degree(χ)
#
K,_ = character_field(χ)
#
degree(K)
#
maximum([degree(minimal_polynomial(x)) for x in values(χ)])

# So, while the character field of χ has degree 4, the degrees of the subfields generated by individual character values is at most 2.

