# Functions for the FS(χ) property: is the character field of χ generated
# by a single character value?


"""
    is_fs(χ::Oscar.GAPGroupClassFunction)

Returns true iff the character field of χ is generated by a single character 
value.
"""
function is_fs(χ::Oscar.GAPGroupClassFunction)
    
    F,_ = character_field(χ)
    fdeg = degree(F)
    for x in values(χ)
        xdeg = degree(minimal_polynomial(x))
        if xdeg == fdeg
            return true
        end
    end
    return false

end

function is_odd_degree(χ::Oscar.GAPGroupClassFunction)
    return is_odd(degree(ZZRingElem, χ))
end

function is_2rational(χ::Oscar.GAPGroupClassFunction)
    return is_odd(conductor(χ))
end

function is_fs2(
    T::Oscar.GAPGroupCharacterTable; 
    q::Integer=1, 
    findall=false,
    log_file::Union{Nothing,AbstractString}=nothing,
    metadata::NamedTuple=(;)
)

    false_list = NamedTuple[]

    if q > 1
        Cq2 = cyclic_group(q^2)
        TCq2 = character_table(Cq2)
        λ = first(χ for χ in TCq2 if is_faithful(χ))
        TH = direct_product(T, TCq2)
        χ = Dict(
            α => direct_product(TH, α, λ)
            for α in T
        )
    else
        χ = Dict(
            α => α
            for α in T
        )
    end
    
    candidates = galois_representatives([ α for α in T if (is_odd_degree(α) || is_2rational(χ[α])) ])
    
    if !isnothing(log_file)
        group_data = (
            table = identifier(T),
            G_order = order(T),
            G_solvable = is_solvable(T),
            G_supersolvable = is_supersolvable(T),
            G_nilpotent = is_nilpotent(T),
            G_perfect = is_perfect(T),
            G_simple = is_simple(T),
            G_quasisimple = is_quasisimple(T),
            G_almost_simple = is_almost_simple(T),
        )
    end

    for α in candidates
        if !is_fs(χ[α])
            
            data = (
                q=q,
                α_position = findfirst(==(α), T),
                α_label = character_label(α),
                α_degree = degree(α),
                α_conductor = conductor(α),
                α_char_field_degree=degree(character_field(α)[1]),
                χ_odd_degree = is_odd_degree(χ[α]),
                χ_two_rational = is_2rational(χ[α]),
                χ_conductor = conductor(χ[α]),
                χ_char_field_degree=degree(character_field(χ[α])[1]),
            )

            push!(false_list, data)

            if !isnothing(log_file)
                data = merge(data, group_data)

                data = reorder_fields(
                    data,
                    (
                        :table,
                        :G_order,
                        :q,
                        :α_position,
                        :α_label,
                        :α_degree,
                        :χ_odd_degree,
                        :χ_two_rational
                    ),
                ) 
                
                append_csv_row(
                    log_file,
                    data,
                    metadata=log_metadata(metadata),
                )
            end

            if !findall
                return false, false_list
            end
        end
    end

    return length(false_list) == 0, false_list 

end

function scan_ctbllib_fs2(; 
    q::Integer=1, 
    show_progress=true, 
    findall=true,
    log_file::Union{Nothing,AbstractString}=nothing
)
    
    names = String.(
        GAP.Globals.AllCharacterTableNames(
            GAP.Globals.IsDuplicateTable,
            false,
        )
    )
    false_list = []
    p = Progress(length(names); desc="Scanning CTblLib")
    
    if !isnothing(log_file)
        metadata = log_metadata(
            packages=(
                oscar=Oscar,
            ),
            extra=(
                gap_version=String(GAP.Globals.GAPInfo.Version),
                ctbllib_version=_gap_package_version("ctbllib"),
                scan_kind="ctbllib-q"*string(q)
            ),
        )
    end

    for name in names
        T = character_table(name)

        res, T_false = is_fs2(T; q=q, findall=findall, log_file=log_file, metadata=metadata)
        append!(false_list, T_false)

        if show_progress
            next!(p; showvalues=[
                (:table, name),
                (:false, length(false_list)),
            ])
        end

    end

end