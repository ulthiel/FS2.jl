"""
    is_cs(χ::Oscar.GAPGroupClassFunction)

Test whether the conductor of the ordinary character `χ` is attained by a
single character value: `conductor(χ) == conductor(χ(g))` for some group
element `g`. Conductors are the least positive integers `n` for which the
character field, respectively the field generated by a value, is contained
in the `n`-th cyclotomic field over the rationals.

This is the CS property from U. Thiel, *On a question by G. Navarro on the
character field generation of odd-degree characters*, §2,
[arXiv:2608.02266](https://arxiv.org/abs/2608.02266).
It is weaker than [`is_fs`](@ref): equal conductors need not mean equal fields.
"""
is_cs(χ::Oscar.GAPGroupClassFunction) = first(is_cs_with_data(χ))

"""
    is_cs_with_data(χ::Oscar.GAPGroupClassFunction)

Return `(res, data)`, where `res` tests conductor attainment as in
[`is_cs`](@ref). The named tuple `data` contains `char_conductor` and
`max_value_conductor`, the largest conductor among the character values.
Every value conductor divides the character conductor, so a successful
test can stop as soon as the latter is attained.
"""
function is_cs_with_data(χ::Oscar.GAPGroupClassFunction)
    c = conductor(χ)
    max_c = 0
    for x in values(χ)
        cx = conductor(x)
        max_c = max(max_c, cx)
        if cx == c
            return true, (char_conductor=c, max_value_conductor=c)
        end
    end
    return false, (char_conductor=c, max_value_conductor=max_c)
end

"""
    is_cs(T::Oscar.GAPGroupCharacterTable)
    is_cs(G::Union{Oscar.GAPGroup, Oscar.FinGenAbGroup})

Test the CS property for every irreducible character of the ordinary
character table `T`. No degree or rationality restriction is imposed.
For a finite group `G`, this is a shortcut for `is_cs(character_table(G))`.
"""
is_cs(T::Oscar.GAPGroupCharacterTable) = all(is_cs, T)

is_cs(G::Union{Oscar.GAPGroup, Oscar.FinGenAbGroup}) =
    is_cs(character_table(G))

"""
    is_cs_with_data(T::Oscar.GAPGroupCharacterTable; findall=false, ...)
    is_cs_with_data(G::Union{Oscar.GAPGroup, Oscar.FinGenAbGroup}; kwargs...)

Test CS for all irreducible characters, up to Galois conjugacy, and return
`(res, failures)`. Stop after the first failure unless `findall=true`.
Each failure records `χ_position`, `χ_label`, `χ_degree`, `χ_faithful`,
`χ_odd_degree`, `χ_two_rational`, `χ_conductor`, and `χ_max_value_conductor`.

As in [`is_fs2_with_data`](@ref), the optional keywords `table_label`,
`findings_log_file`, `scan_log_file`, and `metadata` control CSV logging.
The scan's `false_characters` counts failing Galois representatives.
There is no `q` parameter or degree/rationality restriction.
For a finite group, use its ordinary character table.
"""
function is_cs_with_data(T::Oscar.GAPGroupCharacterTable; kwargs...)
    return _character_attainment_with_data(T; kwargs...) do χ
        res, data = is_cs_with_data(χ)
        return res, (χ_max_value_conductor=data.max_value_conductor,)
    end
end

is_cs_with_data(G::Union{Oscar.GAPGroup, Oscar.FinGenAbGroup}; kwargs...) =
    is_cs_with_data(character_table(G); kwargs...)

"""
    scan_smallgroups_cs(orders::AbstractUnitRange{<:Integer};
                        show_progress=true, findall=true,
                        log_dir=nothing, metadata=(;))

Scan the GAP SmallGroups library for all groups whose orders lie in `orders`
and test CS with [`is_cs_with_data`](@ref). Prime-power orders are skipped:
groups of prime-power order are nilpotent, and CS holds for nilpotent groups.

If `log_dir` is given, failure records and per-group scan records are written
to `findings.csv` and `scan.csv` below a scan-specific directory. The scan
directory is named `smallgroups-FIRST-LAST-cs`, with `-findall` appended when
`findall=true`.
"""
function scan_smallgroups_cs(
    orders::AbstractUnitRange{<:Integer};
    show_progress=true,
    findall=true,
    log_dir::Union{Nothing,AbstractString}=nothing,
    metadata::NamedTuple=(;),
)
    # Every p-group is nilpotent, and CS holds for nilpotent groups; see
    # Boltje--Kleshchev--Navarro--Tiep, arXiv:2507.19618v1, after Theorem 9.6.
    orders_filtered = [n for n in orders if !_is_prime_power(n)]

    for n in orders_filtered
        has_small_groups(n) || throw(ArgumentError(
            "groups of order $n are not available in the SmallGroups library",
        ))
    end

    num_groups = Int(total_number_of_small_groups(orders_filtered))
    @info "Number of groups: " * string(num_groups)

    scan_id = "smallgroups-" * string(first(orders)) * "-" *
              string(last(orders)) * "-cs" * (findall ? "-findall" : "")
    findings_log_file = isnothing(log_dir) ? nothing :
        joinpath(log_dir, scan_id, "findings.csv")
    scan_log_file = isnothing(log_dir) ? nothing :
        joinpath(log_dir, scan_id, "scan.csv")

    false_counter = 0
    # Include the separator in the measured description: otherwise ProgressMeter
    # adds it after sizing the bar, overflowing one column for long day/hour ETAs.
    progress = show_progress ? Progress(num_groups; desc=scan_id * " ") : nothing

    if !isnothing(log_dir)
        metadata = merge(metadata, log_metadata(
            packages=(oscar=Oscar,),
            extra=(
                fs2_git_revision=git_revision(FS2),
                gap_version=String(GAP.Globals.GAPInfo.Version),
                smallgrp_version=_gap_package_version("smallgrp"),
                scan_id=scan_id,
                scan_total=num_groups,
            ),
        ))
    end

    scan_index = 0
    for n in orders_filtered
        for i in 1:number_of_small_groups(n)
            scan_index += 1
            T = character_table(small_group(n, i))
            row_metadata = merge(metadata, (
                scan_index=scan_index,
                group_id=(n, i),
            ))
            _, failures = is_cs_with_data(
                T;
                findall=findall,
                findings_log_file=findings_log_file,
                scan_log_file=scan_log_file,
                table_label="(" * string(n) * "," * string(i) * ")",
                metadata=row_metadata,
            )
            false_counter += length(failures)

            if show_progress
                next!(progress; showvalues=[
                    (:group, (n, i)),
                    (:false, false_counter),
                ])
            end
        end
    end

    return nothing
end
