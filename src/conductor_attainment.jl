"""
    is_cs(χ::Oscar.GAPGroupClassFunction)

Test whether the conductor of the ordinary character `χ` is attained by a
single character value: `conductor(χ) == conductor(χ(g))` for some group
element `g`. Conductors are the least positive integers `n` for which the
character field, respectively the field generated by a value, is contained
in the `n`-th cyclotomic field over the rationals.

This is the CS property from U. Thiel, *On a question by G. Navarro on the
character field generation of odd-degree characters*, §2,
[arXiv:2608.02266](https://arxiv.org/abs/2608.02266).
It is weaker than [`is_fs`](@ref): equal conductors need not mean equal fields.
"""
function is_cs(χ::Oscar.GAPGroupClassFunction)
    c = conductor(χ)
    return any(x -> conductor(x) == c, values(χ))
end

"""
    is_cs(T::Oscar.GAPGroupCharacterTable)
    is_cs(G::Union{Oscar.GAPGroup, Oscar.FinGenAbGroup})

Test the CS property for every irreducible character of the ordinary
character table `T`. No degree or rationality restriction is imposed.
For a finite group `G`, this is a shortcut for `is_cs(character_table(G))`.
"""
is_cs(T::Oscar.GAPGroupCharacterTable) = all(is_cs, T)

is_cs(G::Union{Oscar.GAPGroup, Oscar.FinGenAbGroup}) =
    is_cs(character_table(G))
